"use server";

import { logActionError } from "@/lib/log-action-error";
import { getCookies } from "../../cookies";
import { apiFetch } from "@/lib/api-fetch";

interface ProofDocumentData {
  /** Short-lived link to the PDF. Expires — ask again rather than storing it. */
  url: string;
  filename: string;

  /** The public page the printed QR points at. */
  verificationUrl: string;

  sha256: string;

  /**
   * Rises on every regeneration. The token stays the same, so a QR printed
   * before still reaches the page — the version is what says that copy is not
   * the current one.
   */
  version: number;

  generated_at: string;
  size_bytes: number;

  /**
   * Decision 14.8. 1 = the layout from before the validated model; 2 = the
   * model. Optional: an API older than the field omits all three below.
   */
  layout_version?: number;

  /** What the stored file carries; never claims more than the API recorded. */
  signature?: ProofDocumentSignature;

  /** Whether the server would sign a document generated NOW. */
  signing_available?: boolean;
}

type ProofUnsignedReason =
  | "LEGACY"
  | "NO_CERTIFICATE"
  | "CERTIFICATE_EXPIRED"
  | "CERTIFICATE_INVALID"
  | "SIGNING_DISABLED";

interface ProofDocumentSignature {
  status: "SIGNED" | "UNSIGNED";
  profile: "PADES_AD_RB" | "CMS_DETACHED" | null;
  signer_name: string | null;
  signer_cnpj: string | null;
  cert_not_after: string | null;
  signed_at: string | null;
  unsigned_reason: ProofUnsignedReason | null;
}

interface ActionResponse<T = undefined> {
  success: boolean;
  message: string;
  data?: T;
}

/**
 * The delivery's receipt, generated by the API on the first request.
 *
 * Returns a LINK and a hash, not the bytes: the file lives in the bucket and
 * the browser fetches it straight from there, the same way every other
 * attachment in the product does.
 *
 * The first call for a delivery renders the PDF, which takes a moment. The
 * caller has to show that — a button that looks broken for two seconds is a
 * button people press twice.
 */
const getProofDocument = async (
  businessId: string,
  deliveryId: string,
  regenerate = false,
): Promise<ActionResponse<ProofDocumentData>> => {
  const tokenAccess = await getCookies("tkey");

  if (!tokenAccess) {
    return {
      success: false,
      message: "Token de acesso não encontrado. Faça login novamente.",
    };
  }

  try {
    const params = regenerate ? "?regenerate=true" : "";

    const response = await apiFetch(
      `${process.env.HTTP_REQUEST}/delivery/proof-document/${deliveryId}/business/${businessId}${params}`,
      {
        credentials: "include",
        method: "GET",
        headers: {
          Authorization: `Bearer ${tokenAccess}`,
          "Content-Type": "application/json",
        },
        cache: "no-store",
      },
    );

    const result = await response.json();

    if (!response.ok) {
      return {
        success: false,
        message: result.message || "Houve um erro ao gerar o comprovante.",
      };
    }

    return { success: true, message: result.message, data: result.data };
  } catch (error) {
    logActionError("delivery/get-proof-document", error);
    return {
      success: false,
      message: "Ocorreu um erro inesperado ao gerar o comprovante.",
    };
  }
};

export { getProofDocument };
export type { ProofDocumentData, ProofDocumentSignature, ProofUnsignedReason };
